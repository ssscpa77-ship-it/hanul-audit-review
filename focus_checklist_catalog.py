def _apply_extra_fields(rows: list[FocusCheckRow], extra: dict[str, dict[str, str]]) -> None:
    for r in rows:
        spec = extra.get(r.checklist_id)
        if not spec:
            continue
        for k, v in spec.items():
            setattr(r, k, v)


_apply_extra_fields(LISTED_CHECKLIST_2026 + UNLISTED_CHECKLIST_2026, _EXTRA_FIELDS)


