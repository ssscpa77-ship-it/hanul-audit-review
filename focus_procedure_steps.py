def _build(raw: dict[str, tuple]) -> dict[str, tuple[ProcedureStep, ...]]:
    out: dict[str, tuple[ProcedureStep, ...]] = {}
    for cid, steps in raw.items():
        items: list[ProcedureStep] = []
        for seq, gate, title, ev, dep, red, ftype, note, case in steps:
            items.append(
                ProcedureStep(
                    step_id=f"{cid}-S{seq}",
                    checklist_id=cid,
                    seq=seq,
                    gate=gate,
                    title=title,
                    evidence_keys=_k(ev),
                    depth_keys=_k(dep) or (COMMON_DEPTH_KEYS if gate == "G3" else ()),
                    red_flags=_k(red),
                    failure_type=ftype,
                    review_note=note,
                    case_ref=case,
                )
            )
        out[cid] = tuple(items)
    return out


LISTED_STEPS: dict[str, tuple[ProcedureStep, ...]] = _build(_LISTED_STEPS)
UNLISTED_STEPS: dict[str, tuple[ProcedureStep, ...]] = _build(_UNLISTED_STEPS)
ALL_STEPS: dict[str, tuple[ProcedureStep, ...]] = {**LISTED_STEPS, **UNLISTED_STEPS}


def steps_for(checklist_id: str) -> tuple[ProcedureStep, ...]:
    """체크리스트 ID에 대한 절차 단계 목록."""
    return ALL_STEPS.get(str(checklist_id or "").strip(), ())


def coverage_for(is_listed: bool) -> tuple[IssueCoverage, ...]:
    """상장/비상장별 이슈 수준 필수 조서 커버리지 표."""
    return tuple(c for c in ISSUE_COVERAGE if c.is_listed == bool(is_listed))


def step_count(is_listed: bool | None = None) -> int:
    if is_listed is None:
        return sum(len(v) for v in ALL_STEPS.values())
    src = LISTED_STEPS if is_listed else UNLISTED_STEPS
    return sum(len(v) for v in src.values())


